// 村長の会話。踏破済みダンジョン(meta.clearedDungeons)に応じて台詞を変える。
// 村長＝大崩れの生き残り。同じ道で我が子を斬れず逃げ帰り、三十年門を見張ってきた主人公の鏡。
export function chiefLines(cleared: string[]): StoryLine[] {
  const has = (id: string) => cleared.includes(id)

  if (has('abyss')) {
    return [
      { speaker: '村長', text: '儂が三十年、成せなかったことを、お前は成した。……礼を言う。' },
      {
        speaker: '村長',
        text: 'だが淀みは尽きぬ。北ではまだ、大崩れが広がっている。底で帰りを待つ者もいる。……また、頼めるか。',
      },
    ]
  }
  if (has('darkCastle')) {
    return [
      { speaker: '村長', text: '城も抜けたな。……ここから先は最深部だ。先に、話しておかねばならん。' },
      {
        speaker: '村長',
        text: '儂も大崩れを生き延びた一人だ。攫われた我が子を連れ戻そうと、昔、同じ道を下った。……だが変わり果てたあれを前に、剣を落として逃げ帰った。',
      },
      {
        speaker: '村長',
        text: 'だから言える。底で妹を見つけても、それはもう妹ではない。お前にできるのは、終わらせてやることだけだ。',
      },
    ]
  }
  if (has('silentForest')) {
    return [
      { speaker: '村長', text: '森を抜けたか。……あの静けさの底で、覚えのある声を、拾いはしなかったか。' },
      { speaker: '村長', text: '拾っても、応えるな。止まるな。次は暗黒城だ。' },
      {
        speaker: '村長',
        text: 'かつて王国が深淵を封じんと築き、大崩れに呑まれた城砦。妹を追って下り、還れなかった者たちの、成れの果てでもある。',
      },
    ]
  }
  return [
    { speaker: '村長', text: '妹を、か。止めはせぬ。だが覚えておけ——望んだ分だけ、底は遠い。' },
    { speaker: '村長', text: 'まずは静寂の森だ。急くな。焦った足は止まり、止まった者から攫われる。' },
  ]
}
