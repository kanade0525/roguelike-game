// 村長の会話。踏破済みダンジョン(meta.clearedDungeons)に応じて台詞を変える。
// 村長＝同じ道で我が子を斬れず逃げ帰った過去の探索者（＝主人公の鏡）。
export function chiefLines(cleared: string[]): StoryLine[] {
  const has = (id: string) => cleared.includes(id)

  if (has('abyss')) {
    return [
      { speaker: '村長', text: 'お前は、儂が三十年できなかったことを成した。……礼を言う。' },
      {
        speaker: '村長',
        text: 'だが淀みは尽きぬ。まだ底には、誰かの帰りを待つ者がいる。……また、頼めるか。',
      },
    ]
  }
  if (has('darkCastle')) {
    return [
      { speaker: '村長', text: '暗黒城も抜けたな。……いよいよ最深部だ。一つ、話しておかねばならぬ。' },
      {
        speaker: '村長',
        text: '儂も昔、底まで下った。攫われた我が子を、連れ戻すために。……だが、変わり果てたあれを前に、儂は剣を落とし、逃げ帰った。',
      },
      {
        speaker: '村長',
        text: 'だから言う。底で妹を見つけても、それはもう妹ではない。お前にできるのは——"終わらせて"やることだけだ。',
      },
    ]
  }
  if (has('silentForest')) {
    return [
      { speaker: '村長', text: '森を抜けたか。……あの静けさの中に、聞き覚えのある声を、拾わなかったか。' },
      {
        speaker: '村長',
        text: '拾っても、足を止めるな。次は暗黒城——妹を追って下り、還れなかった者たちの、成れの果てだ。',
      },
    ]
  }
  return [
    { speaker: '村長', text: '妹を、か。……止めはせぬ。だが覚えておけ。深淵は、望みを餌にする。' },
    { speaker: '村長', text: 'まずは静寂の森を抜けよ。装備を整え、決して急ぐな。焦りは、足を止めさせる。' },
  ]
}
